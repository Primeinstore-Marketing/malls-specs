#!/usr/bin/env python3
"""
Regenerates app/lib/mallLocations.ts from OpenStreetMap (via Nominatim).

    python3 app/scripts/fetch-mall-locations.py

Each mall is pinned to an exact OSM element below, so a refresh picks up
edits to that element (a redrawn outline, say) but can never silently
drift to a different place with a similar name. To add or correct a mall,
find it on openstreetmap.org, click it, and copy the id from the URL:
openstreetmap.org/way/147206297 -> 'W147206297' (N = node, R = relation).

Data © OpenStreetMap contributors, ODbL 1.0 — the map credits this.
"""
import json
import pathlib
import urllib.parse
import urllib.request

OSM_IDS = {
    'cresta': 'W140846335',
    'menlyn': 'W147206297',
    'monte-casino': 'W141199310',
    'pavilion': 'W1132687394',
    'southgate': 'R6173914',
    'tygervalley': 'W6238440',
    'bayside': 'W68612598',
    'boardwalk': 'R6676953',
    'brooklyn': 'W1010637464',
    'fourways': 'R7691867',
    'gardens': 'W44559820',
    'gateway': 'W40943223',
    'golden-acre': 'W26114999',
    # 'loch-logan': not on OpenStreetMap as of 2026-10-22.
    'mimosa': 'N3879519356',
    'n1-city': 'W789230883',
    'paarl-mall': 'W170210959',
    'westgate': 'W23403076',
    'canal-walk': 'W429507655',
    'cape-gate': 'W132720471',
    'clearwater': 'W130546857',
    'table-bay': 'W780096343',
    'hype-park': 'W53531986',
    'rosebank': 'W140180089',
    'somerset': 'W792497491',
    'the-glen': 'W154986359',
    'woodlands': 'W619381958',
}

OUT = pathlib.Path(__file__).resolve().parent.parent / 'lib' / 'mallLocations.ts'


def rounded(coords):
    if isinstance(coords[0], (int, float)):
        return [round(coords[0], 6), round(coords[1], 6)]
    return [rounded(c) for c in coords]


def main():
    url = 'https://nominatim.openstreetmap.org/lookup?' + urllib.parse.urlencode(
        {'osm_ids': ','.join(OSM_IDS.values()), 'format': 'jsonv2', 'polygon_geojson': 1}
    )
    request = urllib.request.Request(url, headers={'User-Agent': 'malls-specs/0.1 (mall location snapshot)'})
    results = json.load(urllib.request.urlopen(request, timeout=60))
    by_id = {f"{r['osm_type'][0].upper()}{r['osm_id']}": r for r in results}

    locations = {}
    for key, osm_id in OSM_IDS.items():
        r = by_id.get(osm_id)
        if r is None:
            print(f'  ! {key}: {osm_id} not returned — left out')
            continue
        south, north, west, east = map(float, r['boundingbox'])
        geometry = r['geojson']
        locations[key] = {
            'osm': osm_id,
            'osmName': r.get('name') or '',
            'center': [round(float(r['lon']), 6), round(float(r['lat']), 6)],
            'bounds': [[round(west, 6), round(south, 6)], [round(east, 6), round(north, 6)]],
            'outline': (
                {'type': geometry['type'], 'coordinates': rounded(geometry['coordinates'])}
                if geometry['type'] in ('Polygon', 'MultiPolygon')
                else None
            ),
        }
        print(f"  {key:13} {osm_id:13} {r.get('name')!r}")

    OUT.write_text(
        '/**\n'
        ' * GENERATED by app/scripts/fetch-mall-locations.py — do not edit by hand.\n'
        ' * Mall positions and outlines from OpenStreetMap.\n'
        ' * Data © OpenStreetMap contributors, ODbL 1.0.\n'
        ' */\n\n'
        'export interface MallOutline {\n'
        "  readonly type: 'Polygon' | 'MultiPolygon';\n"
        '  readonly coordinates: readonly unknown[];\n'
        '}\n\n'
        'export interface MallLocation {\n'
        '  /** OpenStreetMap element, e.g. "W147206297" (way 147206297). */\n'
        '  readonly osm: string;\n'
        '  readonly osmName: string;\n'
        '  readonly center: readonly [number, number];\n'
        '  /** [[west, south], [east, north]] */\n'
        '  readonly bounds: readonly [readonly [number, number], readonly [number, number]];\n'
        '  /** Null when OpenStreetMap only has the mall as a single point. */\n'
        '  readonly outline: MallOutline | null;\n'
        '}\n\n'
        'export const MALL_LOCATIONS: Readonly<Record<string, MallLocation>> = '
        + json.dumps(locations, separators=(',', ':'))
        + ';\n'
    )
    print(f'Wrote {len(locations)} malls to {OUT}')


if __name__ == '__main__':
    main()
